//! What a grid in server mode waits for (issue #452): `opengrid-server` with
//! one source, PostgreSQL or SQLite, answering the requests a grid sends while
//! it scrolls — a window of 40 rows, filtered, sorted and grouped by the
//! database. Real HTTP over the loopback, the binary result form, as
//! `createRestProvider` asks; no network beyond that, so the figures are the
//! server and the database.
//!
//! ```sh
//! DATABASE_URL=postgres://$USER@localhost:5432/opengrid_dev \
//!   cargo run --release -p opengrid-server --example server_bench -- postgres 1000000
//! cargo run --release -p opengrid-server --example server_bench -- sqlite 10000000
//! COUNT_CACHE=1 cargo run --release -p opengrid-server --example server_bench -- sqlite 10000000
//! /usr/bin/time -l <target>/release/examples/server_bench postgres 1000000   # peak RSS
//! ```
//!
//! The rows are those of `scripts/measure-queries.mjs`, generated by the
//! database itself (`generate_series`, a recursive CTE) into a table kept for
//! the next run: `bench_orders_<rows>` in PostgreSQL, `target/bench-orders-<rows>.sqlite`.
//! Indexes as a page tuned for these requests would have them: the key `id`,
//! and `(country, amount)` for the filtered window. With `amount` alone,
//! SQLite takes that index for a range over half the table and needs seconds
//! for what the pair answers in milliseconds — the database's indexes decide.
//! Every request runs `RUNS` times after one thrown away; the median and the
//! spread are printed.

use std::time::{Duration, Instant};

use opengrid_connector::Connector;
use opengrid_connector_sqlite::{Connection, SqliteConnector, create_table};
use opengrid_datasource_postgres::PostgresDataSource;
use opengrid_server::{Server, SourcePolicy};
use opengrid_types::Schema;
use tokio::io::{AsyncBufReadExt, AsyncReadExt, AsyncWriteExt, BufReader};
use tokio::net::TcpStream;

type Error = Box<dyn std::error::Error + Send + Sync>;

const RUNS: usize = 9;
const WINDOW: u64 = 40;
const FIELDS: [&str; 10] = [
    "id",
    "customer",
    "country",
    "amount",
    "qty",
    "ratio",
    "flag",
    "ordered_on",
    "created_at",
    "note",
];
/// 2026-03-01 in days since 1970-01-01, the first `ordered_on`.
const MARCH_FIRST: i64 = 20_513;

#[tokio::main]
async fn main() -> Result<(), Error> {
    let args: Vec<String> = std::env::args().collect();
    let (kind, rows) = match (args.get(1), args.get(2).and_then(|n| n.parse::<u64>().ok())) {
        (Some(kind), Some(rows)) if kind == "postgres" || kind == "sqlite" => (kind.clone(), rows),
        _ => {
            eprintln!("usage: server_bench postgres|sqlite <rows>");
            std::process::exit(2);
        }
    };
    let schema: Schema = opengrid_json::from_str(&std::fs::read_to_string(
        repo().join("crates/opengrid-conformance/data/orders.schema.json"),
    )?)?;

    let started = Instant::now();
    let connector: Box<dyn Connector> = if kind == "postgres" {
        Box::new(postgres(rows, schema).await?)
    } else {
        Box::new(sqlite(rows, schema)?)
    };
    eprintln!(
        "{kind}, {rows} rows ready in {:.1} s",
        started.elapsed().as_secs_f64()
    );

    let server = Server::builder()
        .token("bench", std::iter::empty::<(&str, &str)>())
        .timeout(Duration::from_secs(120))
        // The figures are of one request after another asking the same, so the
        // cold ones need the count cache off (issue #457); `COUNT_CACHE=1` turns
        // it on to see what a window costs when its count is remembered.
        .count_cache_ttl(if std::env::var_os("COUNT_CACHE").is_some() {
            Duration::from_secs(60)
        } else {
            Duration::ZERO
        })
        .shared_source(
            "orders",
            connector.into(),
            SourcePolicy {
                allowed_fields: FIELDS.iter().map(|f| f.to_string()).collect(),
                row_filter: None,
            },
        )
        .build()
        .await?;
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await?;
    let address = listener.local_addr()?;
    tokio::spawn(async move { axum::serve(listener, server.router()).await });

    let select = format!("{:?}", FIELDS).replace(' ', "");
    let deep = rows / 2;
    let scenarios = [
        (
            "First window (sort by id)",
            format!(r#"{{"source":"orders","select":{select},"sort":[{{"field":"id"}}],"offset":0,"limit":{WINDOW}}}"#),
        ),
        (
            "Window in the middle (offset rows/2)",
            format!(r#"{{"source":"orders","select":{select},"sort":[{{"field":"id"}}],"offset":{deep},"limit":{WINDOW}}}"#),
        ),
        (
            "Filter country + amount, sort by amount",
            format!(
                r#"{{"source":"orders","select":{select},"filter":{{"and":[{{"field":"country","op":"eq","value":"DE"}},{{"field":"amount","op":"gte","value":"500.00"}}]}},"sort":[{{"field":"amount","direction":"desc"}}],"offset":0,"limit":{WINDOW}}}"#
            ),
        ),
        (
            "Text search in a column (contains, any case)",
            format!(
                r#"{{"source":"orders","select":{select},"filter":{{"field":"customer","op":"icontains","value":"MER 42"}},"sort":[{{"field":"id"}}],"offset":0,"limit":{WINDOW}}}"#
            ),
        ),
        (
            "Group by country, sum and count",
            r#"{"source":"orders","select":["country","total","orders"],"group":["country"],"aggregate":[{"field":"amount","fn":"sum","as":"total"},{"fn":"count","as":"orders"}],"sort":[{"field":"country"}]}"#.to_owned(),
        ),
        (
            "Count of every row only (limit 0)",
            r#"{"source":"orders","select":["id"],"limit":0}"#.to_owned(),
        ),
        (
            "Count of a filter only (limit 0)",
            r#"{"source":"orders","select":["id"],"filter":{"and":[{"field":"country","op":"eq","value":"DE"},{"field":"amount","op":"gte","value":"500.00"}]},"limit":0}"#.to_owned(),
        ),
    ];

    let mut client = Client::connect(&address.to_string()).await?;
    println!("| {kind}, {rows} rows | Median | Range | Answer |");
    println!("|---|---|---|---|");
    for (name, body) in &scenarios {
        let (_, bytes) = client.query(body).await?;
        let mut samples = Vec::with_capacity(RUNS);
        for _ in 0..RUNS {
            let (time, _) = client.query(body).await?;
            samples.push(time);
        }
        samples.sort();
        println!(
            "| {name} | {} | {}–{} | {} |",
            ms(samples[RUNS / 2]),
            ms(samples[0]),
            ms(samples[RUNS - 1]),
            size(bytes)
        );
    }
    Ok(())
}

fn repo() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn ms(time: Duration) -> String {
    let ms = time.as_secs_f64() * 1000.0;
    if ms < 10.0 {
        format!("{ms:.1} ms")
    } else if ms < 1000.0 {
        format!("{ms:.0} ms")
    } else {
        format!("{:.2} s", ms / 1000.0)
    }
}

fn size(bytes: usize) -> String {
    if bytes < 1024 {
        format!("{bytes} B")
    } else {
        format!("{:.1} KiB", bytes as f64 / 1024.0)
    }
}

/// `bench_orders_<rows>` in the database `DATABASE_URL` names, made once.
async fn postgres(rows: u64, schema: Schema) -> Result<PostgresDataSource, Error> {
    let url = std::env::var("DATABASE_URL")
        .unwrap_or_else(|_| "host=localhost dbname=opengrid_dev".to_owned());
    let table = format!("bench_orders_{rows}");
    let (client, connection) = tokio_postgres::connect(&url, tokio_postgres::NoTls).await?;
    tokio::spawn(connection);
    let present: i64 = client
        .query_one(
            "SELECT count(*) FROM pg_tables WHERE schemaname = 'public' AND tablename = $1",
            &[&table],
        )
        .await?
        .get(0);
    if present == 0 {
        eprintln!("writing {table} …");
        client
            .batch_execute(&format!(
                r#"CREATE TABLE {table} (
                     "id" bigint, "customer" text, "country" text, "amount" numeric(12,2),
                     "qty" bigint, "ratio" double precision, "flag" boolean, "ordered_on" date,
                     "created_at" timestamptz, "note" text);
                   INSERT INTO {table}
                     SELECT i, 'Customer ' || (i % 500),
                            (ARRAY['DE','FR','PL','NL','ES','IT','AT','CH'])[i % 8 + 1],
                            (i % 997) + 0.25, i % 40, (i % 100) / 10.0, i % 2 = 0,
                            date '2026-03-01' + (i % 28)::int,
                            ((date '2026-03-01' + (i % 28)::int) + time '12:00') AT TIME ZONE 'UTC',
                            NULL
                     FROM generate_series(1, {rows}) AS i;
                   ALTER TABLE {table} ADD PRIMARY KEY ("id");
                   CREATE INDEX ON {table} ("country", "amount");"#
            ))
            .await?;
        // Outside the statement above: VACUUM refuses a transaction block.
        client
            .batch_execute(&format!("VACUUM ANALYZE {table}"))
            .await?;
    }
    Ok(PostgresDataSource::connect(&url, &table, schema)?)
}

/// `target/bench-orders-<rows>.sqlite`, made once, in the connector's layout:
/// a decimal as a scaled integer, a date as days, a timestamp as microseconds.
fn sqlite(rows: u64, schema: Schema) -> Result<SqliteConnector, Error> {
    let path = repo().join(format!("target/bench-orders-{rows}.sqlite"));
    if !path.exists() {
        eprintln!("writing {} …", path.display());
        std::fs::create_dir_all(repo().join("target"))?;
        let partial = path.with_extension("partial");
        let _ = std::fs::remove_file(&partial);
        let connection = Connection::open(&partial)?;
        create_table(&connection, "orders", &schema)?;
        connection.execute_batch(&format!(
            r#"PRAGMA journal_mode = OFF; PRAGMA synchronous = OFF;
               WITH RECURSIVE s(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM s WHERE i < {rows})
               INSERT INTO orders
                 SELECT i, 'Customer ' || (i % 500),
                        CASE i % 8 WHEN 0 THEN 'DE' WHEN 1 THEN 'FR' WHEN 2 THEN 'PL' WHEN 3 THEN 'NL'
                                   WHEN 4 THEN 'ES' WHEN 5 THEN 'IT' WHEN 6 THEN 'AT' ELSE 'CH' END,
                        (i % 997) * 100 + 25, i % 40, (i % 100) / 10.0, i % 2 = 0,
                        {MARCH_FIRST} + i % 28,
                        ({MARCH_FIRST} + i % 28) * 86400000000 + 43200000000,
                        NULL
                 FROM s;
               CREATE UNIQUE INDEX orders_id ON orders ("id");
               CREATE INDEX orders_country_amount ON orders ("country", "amount");
               ANALYZE;"#
        ))?;
        drop(connection);
        std::fs::rename(&partial, &path)?;
    }
    Ok(SqliteConnector::open(&path, "orders", schema)?)
}

/// HTTP/1.1 on one kept-alive connection: enough for timing a request to
/// the last byte of its answer, nothing more.
struct Client {
    stream: BufReader<TcpStream>,
}

impl Client {
    async fn connect(address: &str) -> Result<Self, Error> {
        let stream = TcpStream::connect(address).await?;
        stream.set_nodelay(true)?;
        Ok(Self {
            stream: BufReader::new(stream),
        })
    }

    /// The time to the answer's last byte, and its length.
    async fn query(&mut self, body: &str) -> Result<(Duration, usize), Error> {
        let request = format!(
            "POST /query/orders HTTP/1.1\r\nHost: 127.0.0.1\r\nAuthorization: Bearer bench\r\n\
             Content-Type: application/json\r\nAccept: application/vnd.opengrid.columns\r\n\
             Content-Length: {}\r\n\r\n{body}",
            body.len()
        );
        let start = Instant::now();
        self.stream.get_mut().write_all(request.as_bytes()).await?;
        let mut status = String::new();
        self.stream.read_line(&mut status).await?;
        let mut length = None;
        let mut chunked = false;
        loop {
            let mut line = String::new();
            self.stream.read_line(&mut line).await?;
            let line = line.trim_end();
            if line.is_empty() {
                break;
            }
            let lower = line.to_ascii_lowercase();
            if let Some(value) = lower.strip_prefix("content-length:") {
                length = Some(value.trim().parse::<usize>()?);
            } else if lower.starts_with("transfer-encoding:") && lower.contains("chunked") {
                chunked = true;
            }
        }
        let mut answer = Vec::new();
        if chunked {
            loop {
                let mut line = String::new();
                self.stream.read_line(&mut line).await?;
                let n = usize::from_str_radix(line.trim_end(), 16)?;
                let mut chunk = vec![0; n + 2];
                self.stream.read_exact(&mut chunk).await?;
                if n == 0 {
                    break;
                }
                answer.extend_from_slice(&chunk[..n]);
            }
        } else {
            answer.resize(length.ok_or("an answer without a length")?, 0);
            self.stream.read_exact(&mut answer).await?;
        }
        let elapsed = start.elapsed();
        if !status.contains(" 200 ") {
            return Err(format!(
                "{}: {}",
                status.trim_end(),
                String::from_utf8_lossy(&answer)
            )
            .into());
        }
        Ok((elapsed, answer.len()))
    }
}
